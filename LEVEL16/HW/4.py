#4)შექმენი 2 ცვლადი number1 და number2–სადაც შეინახავ სხვადასხვა რიცხებს,შენი დავალება არის გაიგო რომელია უფრო მეტი
  #თუ number1-მეტი არის number2-ზე გამოიტანე ასეთი შეტყობინება "პირველი რიცხვი მეტი არის მეორეზე"
  #თუ number2-მეტი არის number1-ზე გამოიტანე ასეთი შეტობინება "მეორე რიცხვი მეტი არის პირველზე"

number1=int(input("შემოიყვანე პირველი რიცხვი"))
number2=int(input("შემოიყვანე მეორე რიცხვი"))
if number1 > number2:
    print("პირველი რიცხვი მეტი არის მეორეზე")
elif number2 > number1:
    print("მეორე რიცხვი მეტი არის პირველზე")